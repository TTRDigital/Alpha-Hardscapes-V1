import { defineArrayMember, defineField, defineType } from "sanity";

export const siteSettings = defineType({
  name: "siteSettings",
  title: "Site settings",
  type: "document",
  groups: [
    { name: "business", title: "Business", default: true },
    { name: "menus", title: "Menus" },
    { name: "forms", title: "Forms" },
    { name: "brand", title: "Logo & video" },
  ],
  fields: [
    defineField({ name: "businessName", type: "string", group: "business", validation: (r) => r.required() }),
    defineField({ name: "phone", title: "Phone (as shown)", type: "string", group: "business", validation: (r) => r.required() }),
    defineField({ name: "phoneE164", title: "Phone (for tap-to-call)", type: "string", group: "business", description: "Format +14752276896", validation: (r) => r.required().regex(/^\+1\d{10}$/) }),
    defineField({ name: "email", type: "string", group: "business" }),
    defineField({ name: "locality", title: "Town", type: "string", group: "business", description: "Town and ZIP only. Never a street address." }),
    defineField({ name: "region", title: "State", type: "string", group: "business", initialValue: "CT" }),
    defineField({ name: "postalCode", title: "ZIP", type: "string", group: "business" }),
    defineField({
      name: "hours",
      title: "Opening hours",
      type: "array",
      group: "business",
      of: [defineArrayMember({ type: "object", name: "hoursRow", fields: [defineField({ name: "days", type: "array", of: [defineArrayMember({ type: "string" })], options: { list: ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"] } }), defineField({ name: "opens", type: "string", description: "24h, e.g. 08:00" }), defineField({ name: "closes", type: "string", description: "24h, e.g. 17:00" })], preview: { select: { d: "days", o: "opens", c: "closes" }, prepare: ({ d, o, c }) => ({ title: `${(d || []).join(", ")}: ${o}–${c}` }) } })],
    }),
    defineField({ name: "areaServed", title: "Areas served", type: "array", group: "business", of: [defineArrayMember({ type: "string" })] }),
    defineField({ name: "socials", title: "Social links", type: "array", group: "business", of: [defineArrayMember({ type: "object", name: "social", fields: [defineField({ name: "label", type: "string" }), defineField({ name: "href", type: "url" })] })] }),
    defineField({ name: "headerNav", title: "Main menu", type: "array", group: "menus", of: [defineArrayMember({ type: "navItem" })] }),
    defineField({ name: "headerCta", title: "Menu button", type: "object", group: "menus", fields: [defineField({ name: "label", type: "string" }), defineField({ name: "formKey", title: "Form it opens", type: "string" })] }),
    defineField({ name: "footerNav", title: "Footer menu", type: "array", group: "menus", of: [defineArrayMember({ type: "navItem" })] }),
    defineField({ name: "popupHeading", title: "Quote form pop-up heading", type: "string", group: "forms" }),
    defineField({
      name: "forms",
      title: "Forms",
      description: "Each form sends to the same CRM webhook and then opens its thank-you page.",
      type: "array",
      group: "forms",
      of: [
        defineArrayMember({
          type: "object",
          name: "formDef",
          fields: [
            defineField({ name: "formKey", title: "Form ID", type: "string", readOnly: true }),
            defineField({ name: "name", title: "Name (sent to the CRM)", type: "string" }),
            defineField({ name: "redirect", title: "Thank-you page", type: "string" }),
            defineField({ name: "tag", title: "CRM tag (optional)", type: "string" }),
            defineField({ name: "button", title: "Button text", type: "string" }),
            defineField({
              name: "fields",
              type: "array",
              of: [defineArrayMember({ type: "object", name: "formField", fields: [defineField({ name: "id", type: "string", readOnly: true }), defineField({ name: "type", type: "string", options: { list: ["text", "tel", "email", "select", "textarea", "acceptance"] } }), defineField({ name: "label", type: "string" }), defineField({ name: "placeholder", type: "string" }), defineField({ name: "required", type: "boolean" }), defineField({ name: "options", type: "array", of: [defineArrayMember({ type: "string" })] }), defineField({ name: "text", title: "Consent text", type: "text", rows: 3 })], preview: { select: { title: "label", subtitle: "type" } } })],
            }),
          ],
          preview: { select: { title: "name", subtitle: "redirect" } },
        }),
      ],
    }),
    defineField({
      name: "authors",
      title: "Blog authors",
      type: "array",
      group: "business",
      of: [defineArrayMember({ type: "object", name: "author", fields: [defineField({ name: "slug", title: "Author page", type: "string", description: "sebastian → /author/sebastian/" }), defineField({ name: "name", type: "string" }), defineField({ name: "role", type: "string" }), defineField({ name: "bio", type: "text", rows: 5 })], preview: { select: { title: "name", subtitle: "role" } } })],
    }),
    defineField({ name: "heroVideo", title: "Home background video (.mp4)", type: "file", group: "brand", options: { accept: "video/mp4" } }),
    defineField({ name: "heroPoster", title: "Home video still (shown while it loads)", type: "photo", group: "brand" }),
    defineField({ name: "logo", type: "photo", group: "brand" }),
    defineField({ name: "logoLight", title: "Logo for dark backgrounds", type: "photo", group: "brand" }),
    defineField({ name: "defaultOgImage", title: "Default share image", type: "photo", group: "brand" }),
  ],
  preview: { prepare: () => ({ title: "Site settings" }) },
});
